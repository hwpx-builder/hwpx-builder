def main() -> int:
    out = sys.argv[1] if len(sys.argv) > 1 else "out/startup_plan_filled.hwpx"
    Path(out).parent.mkdir(parents=True, exist_ok=True)

    if not FORM.exists():
        print(f"양식이 없다: {FORM}")
        return 2

    # 1. .hwp 를 .hwpx 로 변환한다. baseline 검증에 쓰려고 파일로 남긴다.
    try:
        converted = hwp_to_hwpx(FORM, Path(out).parent / "startup_plan_form.hwpx")
    except ConverterUnavailable as exc:
        print(exc)
        print("\n이 예제는 구식 .hwp 양식을 변환해야 하므로 [hwp] 부가 설치가 필요하다.")
        return 1
    print(f"변환: {FORM.name} -> {converted.name}")

    doc = HwpxDocument.open(str(converted))

    # 2. 양식이 "제출 시 삭제" 라고 안내한 문단을 지운다. ※ 로 시작하는
    #    본문 문단이 대상이며, 이 규칙은 양식 종류를 가리지 않는다.
    guidance = clear_guidance(doc)
    print(f"안내문 제거: {guidance.paragraphs}개 문단")

    # 3. 라벨 문구로 칸을 찾아 채운다. 표 인덱스를 쓰지 않는 것이 핵심이다.
    filled, missing = 0, []
    for direction, table in (("right", FILL_RIGHT), ("below", FILL_BELOW)):
        for label, value in table.items():
            ref = find_label(doc, label, direction=direction)
            if ref is None:
                missing.append(label)
                continue
            # 캐시가 지워지기 *전에* 들어갈 자리인지 본다.
            for w in refit_cell(ref):
                print(f"  {w}")
            # 문자열이면 글줄만, 리스트면 글줄과 표가 섞인 블록이다.
            if isinstance(value, str):
                set_cell(doc, ref.cell, value, color=INK, flatten=True)
            else:
                fill_cell(doc, ref.cell, value, color=INK, flatten=True)
            filled += 1

    print(f"채운 칸: {filled}개")
    if missing:
        print(f"  못 찾은 라벨(양식이 개정되었을 수 있다): {missing}")

    # 4. 채운 뒤에 한 칸만 고친다.
    #
    #    실제로는 이 순서로 일한다. 한 번 채워 놓고, 나중에 팀 구성이 바뀌거나
    #    사실관계가 틀린 것을 발견해서 그 칸만 다시 쓴다. 문서 전체를 다시
    #    만들지 않고 라벨로 찾아 해당 칸만 교체하면 된다.
    #
    #    이 단계가 높이 재계산 **앞**에 와야 한다. 뒤에 두면 고친 내용이 반영되지
    #    않은 높이로 남는다.
    team = find_label(doc, "팀 구성원 소개 및 역량", direction="below")
    if team is not None:
        set_cell(doc, team.cell, TEAM_REVISED, color=INK, flatten=True)
        print(f"수정: {team.path} 팀 구성원")

    # 5. 행 높이를 내용에 맞춘다.
    #
    #    `refit_cell` 은 편집 *전* 의 레이아웃 캐시와 비교하는 방식이라 여기서는
    #    쓸 수 없다. 채우는 순간 캐시가 지워지므로 비교할 대상이 사라진다.
    #    그래서 표 단위로 다시 계산한다.
    #
    #    평소에는 남이 만든 표에 `autofit` 을 쓰지 말라는 것이 규칙이다(규칙 8).
    #    행 높이 = 그 행 셀 높이의 최댓값이라는 모델이 병합 표에서 성립하지 않기
    #    때문이다. **그래서 병합 여부를 먼저 확인하고, 병합이 있으면 손대지
    #    않는다.** 이 양식은 병합이 없어서 안전하다.
    tables = {id(c.table): c.table for c in iter_cells(doc) if c.depth == 0}
    merged = [t for t in tables.values() if has_merged_cells(t)]
    if merged:
        print(f"병합 표 {len(merged)}개 발견. 높이 조정을 건너뛴다 "
              f"(한글이 문서를 열 때 다시 배치한다).")
    else:
        # 이 문서의 실제 본문 크기를 쓴다. autofit 기본값 10 pt 로 계산하면
        # 12 pt 양식에서 줄 수를 적게 잡아 칸이 넘친다.
        pt = dominant_font_pt(doc)
        for t in tables.values():
            autofit(t, font_pt=pt)
        print(f"행 높이 재계산: 표 {len(tables)}개 (본문 {pt:g} pt 기준)")

    doc.save_to_path(out)
    print(f"saved: {out}")
    print()

    # 6. 원본과 대조해 검증한다. 편집 범위와 낡은 캐시가 여기서 드러난다.
    print(verify(out, baseline=str(converted)).render())
    return 0


